function parseWeatherKey(mainStr) {
  if (!mainStr) return "clear";
  const s = mainStr.toLowerCase();
  if (s.includes("clear") || s.includes("sun")) return "clear";
  if (s.includes("cloud")) return "clouds";
  if (s.includes("rain")) return "rain";
  if (s.includes("thunder")) return "thunder";
  if (s.includes("drizzle")) return "drizzle";
  if (s.includes("snow")) return "snow";
  if (s.includes("mist") || s.includes("fog")) return "mist";
  return "clear";
}

/* Formateadores de Fechas */
function formatCurrentDate(dateObj) {
  const t = I18N[appState.language];
  const dayName = t.daysOfWeek[dateObj.getDay()];
  const dayNum = dateObj.getDate();
  const monthName = t.months[dateObj.getMonth()];

  if (appState.language === "es") {
    return `${dayName}, ${dayNum} de ${monthName}`;
  } else if (appState.language === "fr") {
    return `${dayName} ${dayNum} ${monthName}`;
  } else {
    return `${dayName}, ${dayNum} ${monthName}`;
  }
}

function formatShortDate(dateObj) {
  const t = I18N[appState.language];
  return `${dateObj.getDate()} ${t.months[dateObj.getMonth()]}`;
}

function formatFullDayHeader(dateObj) {
  const t = I18N[appState.language];
  const dayName = t.daysOfWeek[dateObj.getDay()];
  const dayNum = dateObj.getDate();
  const monthName = t.months[dateObj.getMonth()];
  return `${dayName}, ${dayNum} ${monthName}`;
}

/* Resumen Diario Dinámico */
function buildDynamicDailySummary(
  temp,
  feels,
  min,
  max,
  conditionKey,
  windKmh,
  humidity,
) {
  const lang = appState.language;
  const isWarm = temp >= 22;
  const isRainy =
    conditionKey === "rain" ||
    conditionKey === "thunder" ||
    conditionKey === "drizzle";
  const isWindy = windKmh > 18;

  const tTemp = convertTemp(temp);
  const tFeels = convertTemp(feels);
  const tMin = convertTemp(min);
  const tMax = convertTemp(max);

  const signFeels = tFeels > 0 ? `+${tFeels}` : `${tFeels}`;
  const signTemp = tTemp > 0 ? `+${tTemp}` : `${tTemp}`;

  if (lang === "es") {
    let sensationDesc = "";
    if (feels > temp + 2) {
      sensationDesc = "Se siente más cálido debido al sol y humedad ambiental.";
    } else if (feels < temp - 2) {
      sensationDesc =
        "El viento genera una sensación térmica más fresca que la temperatura real.";
    } else {
      sensationDesc = isWarm
        ? "Día templado con radiación solar agradable."
        : "Condición térmica estable durante la jornada.";
    }

    let extraNote = "";
    if (isRainy)
      extraNote = "Se prevén precipitaciones intermitentes; lleva paraguas.";
    else if (isWindy)
      extraNote = "Ráfagas de viento presentes a lo largo del día.";
    else if (humidity > 75) extraNote = "Ambiente húmedo con alta nubosidad.";
    else extraNote = "Cielo despejado favorable para actividades exteriores.";

    return `Ahora la sensación es de ${signFeels}°, real de ${signTemp}°. ${sensationDesc} ${extraNote} Hoy la temperatura oscilará entre ${tMin}° y ${tMax}°.`;
  } else if (lang === "fr") {
    let sensationDesc = "";
    if (feels > temp + 2) {
      sensationDesc =
        "Il fait plus chaud en raison de l'ensoleillement direct.";
    } else if (feels < temp - 2) {
      sensationDesc =
        "Le vent accentue une sensation plus fraîche que la température mesurée.";
    } else {
      sensationDesc = isWarm
        ? "Journée agréable et ensoleillée."
        : "Température stable tout au long de la journée.";
    }

    let extraNote = "";
    if (isRainy) extraNote = "Précipitations attendues; prévoyez un parapluie.";
    else if (isWindy) extraNote = "Rafales de vent notables sur le secteur.";
    else if (humidity > 75)
      extraNote = "Humidité élevée avec passages nuageux.";
    else extraNote = "Ciel bien dégagé propice aux sorties.";

    return `Ressenti de ${signFeels}°, actuellement ${signTemp}°. ${sensationDesc} ${extraNote} Aujourd'hui, les températures varieront entre ${tMin}° et ${tMax}°.`;
  } else {
    let sensationDesc = "";
    if (feels > temp + 2) {
      sensationDesc =
        "It feels warmer because of direct sunlight and moisture.";
    } else if (feels < temp - 2) {
      sensationDesc = "Breezy conditions make it feel cooler than measured.";
    } else {
      sensationDesc = isWarm
        ? "Warm and comfortable atmospheric conditions."
        : "Consistent temperature throughout the day.";
    }

    let extraNote = "";
    if (isRainy)
      extraNote = "Intermittent rainfall is expected; keep an umbrella handy.";
    else if (isWindy)
      extraNote = "Notable wind gusts expected throughout the area.";
    else if (humidity > 75)
      extraNote = "High relative humidity with cloudy intervals.";
    else extraNote = "Clear skies ideal for outdoor activities.";

    return `Now it feels like ${signFeels}°, actually ${signTemp}°. ${sensationDesc} ${extraNote} Today, temperatures are expected between ${tMin}° and ${tMax}°.`;
  }
}

