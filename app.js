function initLocalStorageState() {
  try {
    const savedLocs = localStorage.getItem("app_weather_locations");
    if (savedLocs) {
      const parsed = JSON.parse(savedLocs);
      if (Array.isArray(parsed) && parsed.length > 0)
        appState.locations = parsed;
    }

    const savedCity = localStorage.getItem("app_current_city");
    if (savedCity && appState.locations.includes(savedCity)) {
      appState.currentCity = savedCity;
    } else {
      appState.currentCity = appState.locations[0];
    }

    const savedTemp = localStorage.getItem("app_temp_unit");
    if (savedTemp) appState.tempUnit = savedTemp;

    const savedWind = localStorage.getItem("app_wind_unit");
    if (savedWind) appState.windUnit = savedWind;

    const savedTheme = localStorage.getItem("app_theme");
    if (savedTheme) appState.theme = savedTheme;

    const savedColorTheme = localStorage.getItem("app_color_theme");
    if (savedColorTheme) appState.colorTheme = savedColorTheme;

    const savedLang = localStorage.getItem("app_language");
    if (savedLang) appState.language = savedLang;

    const savedKey = localStorage.getItem("app_owm_api_key");
    if (savedKey) appState.apiKey = savedKey;
  } catch (err) {
    console.warn("Storage restricted", err);
  }
}

function persistState() {
  try {
    localStorage.setItem(
      "app_weather_locations",
      JSON.stringify(appState.locations),
    );
    localStorage.setItem("app_current_city", appState.currentCity);
    localStorage.setItem("app_temp_unit", appState.tempUnit);
    localStorage.setItem("app_wind_unit", appState.windUnit);
    localStorage.setItem("app_theme", appState.theme);
    localStorage.setItem("app_color_theme", appState.colorTheme);
    localStorage.setItem("app_language", appState.language);
    localStorage.setItem("app_owm_api_key", appState.apiKey);
  } catch (e) {}
}

/* Conversión de Unidades */
function convertTemp(celsius) {
  if (appState.tempUnit === "F") {
    return Math.round((celsius * 9) / 5 + 32);
  }
  return Math.round(celsius);
}

function convertWind(speedKmh) {
  if (appState.windUnit === "mph") {
    return `${(speedKmh * 0.621371).toFixed(1)} mph`;
  } else if (appState.windUnit === "ms") {
    return `${(speedKmh / 3.6).toFixed(1)} m/s`;
  }
  return `${Math.round(speedKmh)} km/h`;
}

