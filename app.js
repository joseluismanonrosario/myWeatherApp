function refreshSystemClock() {
  const now = new Date();
  let hours = now.getHours();
  let minutes = now.getMinutes();
  document.getElementById("clock-display").textContent =
    `${hours}:${minutes < 10 ? "0" + minutes : minutes}`;
}

