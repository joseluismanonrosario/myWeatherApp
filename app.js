function saveApiKey() {
  const keyInput = document.getElementById("input-owm-token");
  const key = keyInput.value.trim();
  const t = I18N[appState.language];

  if (appState.apiKey && (!key || key === appState.apiKey)) {
    appState.apiKey = "";
    keyInput.value = "";
    persistState();
    showToast(t.apiRemoved);
    loadWeatherDataForCity(appState.currentCity);
    return;
  }

  appState.apiKey = key;
  persistState();
  showToast(key ? t.apiSaved : t.apiRemoved);
  loadWeatherDataForCity(appState.currentCity);
}

