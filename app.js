/* ================= SISTEMA DE AUTOCOMPLETADO ================= */
let autocompleteDebounceTimer = null;
let activeAutocompleteIndex = -1;

function handleCityInput(val) {
  clearTimeout(autocompleteDebounceTimer);
  const query = val.trim();

  if (query.length < 2) {
    hideAutocomplete();
    return;
  }

  autocompleteDebounceTimer = setTimeout(() => {
    fetchCitySuggestions(query);
  }, 280);
}

async function fetchCitySuggestions(query) {
  if (appState.apiKey && appState.apiKey.trim().length > 15) {
    try {
      const url = `https://api.openweathermap.org/geo/1.0/direct?q=${encodeURIComponent(query)}&limit=5&appid=${appState.apiKey.trim()}`;
      const res = await fetch(url);
      if (res.ok) {
        const data = await res.json();
        if (Array.isArray(data) && data.length > 0) {
          const suggestions = data.map((item) => ({
            name: item.name,
            country: item.country,
            state: item.state || "",
            label: item.state
              ? `${item.name}, ${item.state}, ${item.country}`
              : `${item.name}, ${item.country}`,
          }));
          renderAutocompleteDropdown(suggestions);
          return;
        }
      }
    } catch (e) {
      console.warn("Geocoding API error, using catalog fallback", e);
    }
  }

  const normalizedQuery = query
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "");
  const matches = VERIFIED_CITIES_CATALOG.filter((c) => {
    const normName = c.name
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "");
    const normLabel = c.label
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "");
    return (
      normName.includes(normalizedQuery) || normLabel.includes(normalizedQuery)
    );
  }).slice(0, 6);

  renderAutocompleteDropdown(matches);
}

function renderAutocompleteDropdown(items) {
  const container = document.getElementById("city-autocomplete-list");
  container.innerHTML = "";
  activeAutocompleteIndex = -1;
  const t = I18N[appState.language];

  if (!items || items.length === 0) {
    const empty = document.createElement("div");
    empty.className = "autocomplete-empty";
    empty.textContent = t.noSuggestions;
    container.appendChild(empty);
    container.classList.add("show");
    return;
  }

  items.forEach((item, idx) => {
    const btn = document.createElement("button");
    btn.type = "button";
    btn.className = "autocomplete-item";
    btn.setAttribute("data-index", idx);

    btn.innerHTML = `
          <svg viewBox="0 0 24 24">
            <path stroke-linecap="round" stroke-linejoin="round" d="M12 21.5c-4.4 0-8-3.6-8-8 0-4.8 8-12 8-12s8 7.2 8 12c0 4.4-3.6 8-8 8z"/>
          </svg>
          <span class="city-bold">${item.name}</span>
          <span class="country-badge">${item.country || ""}</span>
        `;

    btn.onclick = (e) => {
      e.stopPropagation();
      selectAutocompleteItem(item.label || `${item.name}, ${item.country}`);
    };

    container.appendChild(btn);
  });

  container.classList.add("show");
}

function hideAutocomplete() {
  const container = document.getElementById("city-autocomplete-list");
  if (container) {
    container.classList.remove("show");
    container.innerHTML = "";
  }
  activeAutocompleteIndex = -1;
}

function selectAutocompleteItem(cityName) {
  const input = document.getElementById("input-new-city-name");
  input.value = cityName;
  hideAutocomplete();
  submitNewCity();
}

function handleCityInputKeydown(event) {
  const container = document.getElementById("city-autocomplete-list");
  const items = container.querySelectorAll(".autocomplete-item");

  if (event.key === "ArrowDown") {
    if (!container.classList.contains("show") || items.length === 0) return;
    event.preventDefault();
    activeAutocompleteIndex = (activeAutocompleteIndex + 1) % items.length;
    updateAutocompleteHighlight(items);
  } else if (event.key === "ArrowUp") {
    if (!container.classList.contains("show") || items.length === 0) return;
    event.preventDefault();
    activeAutocompleteIndex =
      (activeAutocompleteIndex - 1 + items.length) % items.length;
    updateAutocompleteHighlight(items);
  } else if (event.key === "Enter") {
    event.preventDefault();
    if (
      container.classList.contains("show") &&
      activeAutocompleteIndex >= 0 &&
      items[activeAutocompleteIndex]
    ) {
      items[activeAutocompleteIndex].click();
    } else {
      submitNewCity();
    }
  } else if (event.key === "Escape") {
    hideAutocomplete();
  }
}

function updateAutocompleteHighlight(items) {
  items.forEach((item, i) => {
    item.classList.toggle("highlighted", i === activeAutocompleteIndex);
    if (i === activeAutocompleteIndex) {
      item.scrollIntoView({ block: "nearest", behavior: "smooth" });
    }
  });
}

function submitNewCity() {
  const input = document.getElementById("input-new-city-name");
  const name = input.value.trim();
  const t = I18N[appState.language];

  if (!name) return;

  if (!appState.locations.includes(name)) {
    appState.locations.push(name);
    persistState();
    renderConfigLocations();
    showToast(`${t.cityAdded}: "${name}"`);
  }
  closeAddCityForm();
}

function deleteLocation(name) {
  const t = I18N[appState.language];

  if (appState.locations.length <= 1) {
    showToast(t.atLeastOneCity);
    return;
  }

  appState.locations = appState.locations.filter((item) => item !== name);

  if (
    appState.currentCity.toLowerCase() ===
    name.split(",")[0].trim().toLowerCase()
  ) {
    appState.currentCity = appState.locations[0].split(",")[0].trim();
    loadWeatherDataForCity(appState.locations[0]);
  }

  persistState();
  renderConfigLocations();
  showToast(t.cityRemoved);
}

